def load_milestone2_and_prepare(config: dict) -> dict:
    in_path = os.path.join(config["output_dir"], config["input_blend"])
    if not os.path.exists(in_path):
        raise FileNotFoundError(f"Milestone 2 .blend not found at {in_path}")

    log(f"Loading Milestone 2 Blender file: {in_path}")
    bpy.ops.wm.open_mainfile(filepath=in_path)

    scene = bpy.context.scene
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.scale_length = 1.0

    # Remove Milestone 1 reference placeholders (GROUND_TURF_REFERENCE, PITCH_AXIS_REFERENCE)
    # while keeping URBAN_SURROUND_GROUND so renders never sit in a black void
    for old_name in ("GROUND_TURF_REFERENCE", "PITCH_AXIS_REFERENCE"):
        old_obj = bpy.data.objects.get(old_name)
        if old_obj is not None:
            bpy.data.objects.remove(old_obj, do_unlink=True)

    cols = {}
    for cname in [
        "PLAYING_SURFACE",
        "VENUE_FURNITURE",
        "FLOODLIGHT_TOWERS",
        "RUNTIME_HOOK_EMPTIES",
        "RENDER_CAMERAS",
    ]:
        col = bpy.data.collections.get(cname)
        if col is not None:
            for obj in list(col.objects):
                bpy.data.objects.remove(obj, do_unlink=True)
        else:
            col = bpy.data.collections.new(cname)
            scene.collection.children.link(col)
        cols[cname] = col

    return cols


def build_milestone3_materials(config: dict, tex_info: dict) -> dict:
    """
    Creates PBR materials wired to the newly baked 2K image textures on disk:
    - M3_Outfield_PBR_Turf (wired to 2K albedo, normal, roughness, ao)
    - M3_Pitch_Clay_22Yd (wired to 2K pitch albedo, normal, roughness)
    - M3_Ash_Wood_Stumps, M3_White_Painted_Decal, M3_Boundary_Cushion_Blue, M3_Boundary_Cushion_White
    - M3_Perimeter_Ad_Board (wired to UV0 sponsor ribbon texture)
    - M3_Scoreboard_Screen & M3_Corner_LED_Screen (wired to UV0 scoreboard texture + emissive boost)
    - M3_SightScreen_MatteWhite, M3_Pavilion_Concrete, M3_Pavilion_Glass, M3_Dugout_Canopy
    - M3_Floodlight_Galvanized_Steel, M3_Floodlight_Lamp_Housing,
      M3_Floodlight_Emissive_Bank_A, M3_Floodlight_Emissive_Bank_B
    """
    log("Building Milestone 3 PBR materials wired to 2K baked textures...")
    mats = {}

    def load_img(rel_key: str, non_color: bool = False) -> bpy.types.Image:
        p = tex_info[rel_key]["path"]
        img = bpy.data.images.load(p, check_existing=True)
        if non_color:
            img.colorspace_settings.name = "Non-Color"
        return img

    # 1. Outfield Turf Material (2K Albedo + Normal + Roughness + AO)
    mat_turf = bpy.data.materials.new("M3_Outfield_PBR_Turf")
    mat_turf.use_nodes = True
    nt = mat_turf.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    bsdf = nt.nodes.new("ShaderNodeBsdfPrincipled")
    if "Specular" in bsdf.inputs:
        bsdf.inputs["Specular"].default_value = 0.22

    uv_node = nt.nodes.new("ShaderNodeUVMap")
    uv_node.uv_map = "UVMap"

    tex_alb = nt.nodes.new("ShaderNodeTexImage")
    tex_alb.image = load_img("grass_outfield/albedo.png", non_color=False)
    tex_ao = nt.nodes.new("ShaderNodeTexImage")
    tex_ao.image = load_img("grass_outfield/ao.png", non_color=True)
    mix_ao = nt.nodes.new("ShaderNodeMixRGB")
    mix_ao.blend_type = "MULTIPLY"
    mix_ao.inputs["Fac"].default_value = 0.65

    tex_rough = nt.nodes.new("ShaderNodeTexImage")
    tex_rough.image = load_img("grass_outfield/roughness.png", non_color=True)

    tex_norm = nt.nodes.new("ShaderNodeTexImage")
    tex_norm.image = load_img("grass_outfield/normal.png", non_color=True)
    norm_map = nt.nodes.new("ShaderNodeNormalMap")
