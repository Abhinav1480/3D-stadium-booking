def write_png_rgb_or_gray(filepath: str, arr: np.ndarray) -> int:
    """
    Writes an 8-bit RGB (H, W, 3) or Grayscale (H, W) numpy uint8 array to a
    standard PNG file using Python's built-in zlib + struct.
    """
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    # Flip vertically so row 0 is top of image in standard UV space
    arr = np.flipud(arr)
    if arr.ndim == 2:
        height, width = arr.shape
        color_type = 0  # Grayscale
        raw_rows = b"".join(b"\x00" + arr[y].tobytes() for y in range(height))
    else:
        height, width, channels = arr.shape
        color_type = 2 if channels == 3 else 6
        raw_rows = b"".join(b"\x00" + arr[y].tobytes() for y in range(height))

    def make_chunk(chunk_type: bytes, data: bytes) -> bytes:
        crc = zlib.crc32(chunk_type + data) & 0xFFFFFFFF
        return struct.pack(">I", len(data)) + chunk_type + data + struct.pack(">I", crc)

    ihdr = struct.pack(">IIBBBBB", width, height, 8, color_type, 0, 0, 0)
    compressed = zlib.compress(raw_rows, level=4)
    png_bytes = (
        b"\x89PNG\r\n\x1a\n"
        + make_chunk(b"IHDR", ihdr)
        + make_chunk(b"IDAT", compressed)
        + make_chunk(b"IEND", b"")
    )
    with open(filepath, "wb") as f:
        f.write(png_bytes)
    return len(png_bytes)


def bake_milestone3_2k_textures(config: dict) -> dict:
    """
    Bakes 2K (2048x2048) mipmap-friendly PBR maps for the outfield turf (albedo,
    normal, roughness, ao), pitch clay (2048x512 albedo, normal, roughness),
    perimeter ad board ribbon (2048x256), and scoreboard/LED canvas (1024x512).
    """
    t0 = time.time()
    tex_root = config["texture_dir"]
    log(f"Baking 2K (2048x2048) PBR textures into {tex_root} ...")
    written = {}

    # --------------------------------------------------------------------------
    # A. 2K (2048x2048) OUTFIELD GRASS PBR MAPS (WORLD-SPACE PLANAR [-80..80] m)
    #    - Clean alternating mower bands (6.0 m pitch along X + subtle 8.0 m Y cross-cut
    #      + gentle diagonal check, completely free of concentric ripples or aliasing)
    #    - Realistic brown/sandy soil wear patches near bowler run-ups, pitch perimeter,
    #      and sight-screen / boundary approaches
    # --------------------------------------------------------------------------
    res = 2048
    lin = np.linspace(-80.0, 80.0, res, dtype=np.float32)
    X, Y = np.meshgrid(lin, lin)

    # Smooth anti-aliased mower stripes (smooth cosine blend, no hard step aliasing)
    stripe_x = 0.5 + 0.5 * np.tanh(2.2 * np.cos(X * (math.pi / 5.5)))
    stripe_y = 0.5 + 0.5 * np.tanh(1.8 * np.cos(Y * (math.pi / 7.5)))
    diag_1 = 0.5 + 0.5 * np.sin((X + Y) * (math.pi / 11.0))
    mower_mask = np.clip(0.68 * stripe_x + 0.22 * stripe_y + 0.10 * diag_1, 0.0, 1.0)

    # Multi-scale organic turf variation (no radial/concentric terms!)
    rng = np.random.default_rng(42)
    # Low-frequency organic patchiness via summed spatial sinusoids
    organic = (
        0.35 * np.sin(X * 0.09 + 0.4) * np.cos(Y * 0.08 - 0.2)
        + 0.25 * np.sin(X * 0.23 - Y * 0.19 + 1.1)
        + 0.20 * np.cos(X * 0.47 + Y * 0.41 - 0.7)
        + 0.20 * rng.normal(0.0, 0.35, size=(res, res)).astype(np.float32)
    )
    organic = np.clip(0.5 + 0.5 * organic, 0.0, 1.0)

    # Soil wear mask near bowler run-ups (x in [-19..-9.5] and [9.5..19], |y| < 1.8),
    # pitch edge apron (|x| < 11.8, |y| < 2.35), and South Pavilion walkout (x in [-4..4], y in [-72..-64])
    runup_w = np.exp(-(((np.abs(X) - 13.2) / 3.4) ** 2) - (((np.abs(Y) - 0.55) / 0.85) ** 2)) * 0.92
    crease_edge_w = np.exp(-(((np.abs(X) - 9.2) / 1.8) ** 2) - (((np.abs(Y) - 1.65) / 0.65) ** 2)) * 0.88
    pitch_apron_w = np.exp(-((X / 11.6) ** 6) - ((Y / 2.15) ** 4)) * 0.78
    umpire_w = np.exp(-(((np.abs(X) - 11.4) / 1.4) ** 2) - ((Y / 0.75) ** 2)) * 0.85
    pavilion_walk_w = np.exp(-((X / 3.2) ** 2) - (((Y + 68.5) / 4.2) ** 2)) * 0.82
    soil_wear = np.clip((runup_w + crease_edge_w + pitch_apron_w + umpire_w + pavilion_walk_w) * (0.78 + 0.32 * organic), 0.0, 0.95)

    # Base turf colors (dark lush band vs lighter sunlit-cut band vs worn sandy loam soil)
    col_dark_grass = np.array([26.0, 82.0, 28.0], dtype=np.float32)
    col_light_grass = np.array([66.0, 146.0, 52.0], dtype=np.float32)
    col_soil = np.array([156.0, 126.0, 86.0], dtype=np.float32)

    grass_rgb = (
        col_dark_grass[None, None, :] * (1.0 - mower_mask[:, :, None])
        + col_light_grass[None, None, :] * mower_mask[:, :, None]
    )
    # Add subtle organic chlorophyll variation
    grass_rgb *= (0.90 + 0.18 * organic[:, :, None])

    albedo_rgb = (
        grass_rgb * (1.0 - soil_wear[:, :, None])
        + col_soil[None, None, :] * soil_wear[:, :, None]
    )
    albedo_u8 = np.clip(albedo_rgb, 0, 255).astype(np.uint8)

    # Normal map: mower lay direction tilts normal X slightly, plus fine blade micro-relief
    fine_dx = rng.normal(0.0, 0.08, size=(res, res)).astype(np.float32) + 0.05 * (mower_mask - 0.5)
    fine_dy = rng.normal(0.0, 0.08, size=(res, res)).astype(np.float32) + 0.03 * (stripe_y - 0.5)
    norm_u8 = np.zeros((res, res, 3), dtype=np.uint8)
    norm_u8[:, :, 0] = np.clip(128.0 + fine_dx * 110.0, 0, 255).astype(np.uint8)
    norm_u8[:, :, 1] = np.clip(128.0 + fine_dy * 110.0, 0, 255).astype(np.uint8)
    norm_u8[:, :, 2] = 248

    # Roughness map: alternating mower sheen (0.52 vs 0.65) + higher roughness on soil (0.84)
    rough_val = (0.65 - 0.13 * mower_mask + 0.05 * organic) * (1.0 - soil_wear) + 0.84 * soil_wear
    rough_u8 = np.clip(rough_val * 255.0, 0, 255).astype(np.uint8)

    # AO map
    ao_val = 0.88 + 0.10 * mower_mask - 0.08 * soil_wear
    ao_u8 = np.clip(ao_val * 255.0, 0, 255).astype(np.uint8)

    outfield_dir = os.path.join(tex_root, "grass_outfield")
    for fname, arr in [
        ("albedo.png", albedo_u8),
        ("normal.png", norm_u8),
        ("roughness.png", rough_u8),
        ("ao.png", ao_u8),
    ]:
        p = os.path.join(outfield_dir, fname)
        sz = write_png_rgb_or_gray(p, arr)
        written[f"grass_outfield/{fname}"] = {"path": p, "size_bytes": sz, "resolution": "2048x2048"}

    # --------------------------------------------------------------------------
    # B. 2K PITCH CLAY PBR MAPS (2048x512 MAPPED TO [-11.2..11.2] x [-1.525..1.525])
    #    - Rolled beige cricket clay, darker footmark wear zones, and crisp white
    #      bowling creases (x = +/-10.06 m), popping creases (x = +/-8.84 m),
    #      and return creases (y = +/-1.32 m)
    # --------------------------------------------------------------------------
    pw, ph = 2048, 512
    px = np.linspace(-11.20, 11.20, pw, dtype=np.float32)
    py = np.linspace(-1.525, 1.525, ph, dtype=np.float32)
    PX, PY = np.meshgrid(px, py)

    clay_noise = (
        0.5
        + 0.25 * np.sin(PX * 1.9) * np.cos(PY * 3.4)
        + 0.25 * rng.normal(0.0, 0.22, size=(ph, pw)).astype(np.float32)
    )
    clay_noise = np.clip(clay_noise, 0.0, 1.0)

    # Footmark & good-length bounce darkening near x = +/-7.5..9.5 m
    footmarks = (
        np.exp(-(((np.abs(PX) - 8.4) / 1.35) ** 2) - (((PY - 0.35) / 0.42) ** 2)) * 0.65
        + np.exp(-(((np.abs(PX) - 6.2) / 2.20) ** 2) - ((PY / 0.55) ** 2)) * 0.45
    )
    footmarks = np.clip(footmarks, 0.0, 0.78)

    col_clay_base = np.array([204.0, 182.0, 142.0], dtype=np.float32)
    col_clay_dark = np.array([144.0, 120.0, 86.0], dtype=np.float32)
    pitch_rgb = (
        col_clay_base[None, None, :] * (0.92 + 0.14 * clay_noise[:, :, None]) * (1.0 - footmarks[:, :, None])
        + col_clay_dark[None, None, :] * footmarks[:, :, None]
    )

    # Crisp white painted creases (line width = 0.05 m)
    # 1. Bowling creases at x = +/-10.06 m (spanning between return creases |y| <= 1.32 m)
    bowling_crease = (np.abs(np.abs(PX) - 10.06) <= 0.032) & (np.abs(PY) <= 1.34)
    # 2. Popping creases at x = +/-8.84 m (1.22 m in front of bowling crease, |y| <= 1.52 m)
    popping_crease = (np.abs(np.abs(PX) - 8.84) <= 0.032) & (np.abs(PY) <= 1.50)
    # 3. Return creases at y = +/-1.32 m for |x| in [8.84, 11.20]
    return_crease = (np.abs(np.abs(PY) - 1.32) <= 0.032) & (np.abs(PX) >= 8.81) & (np.abs(PX) <= 11.20)

    crease_mask = bowling_crease | popping_crease | return_crease
    pitch_rgb[crease_mask] = np.array([246.0, 246.0, 242.0], dtype=np.float32)

    pitch_albedo_u8 = np.clip(pitch_rgb, 0, 255).astype(np.uint8)
    pitch_rough_u8 = np.clip((0.76 - 0.12 * footmarks + 0.06 * clay_noise) * 255.0, 0, 255).astype(np.uint8)
    pitch_norm_u8 = np.zeros((ph, pw, 3), dtype=np.uint8)
    pitch_norm_u8[:, :, 0] = np.clip(128.0 + rng.normal(0.0, 9.0, size=(ph, pw)), 0, 255).astype(np.uint8)
    pitch_norm_u8[:, :, 1] = np.clip(128.0 + rng.normal(0.0, 9.0, size=(ph, pw)), 0, 255).astype(np.uint8)
    pitch_norm_u8[:, :, 2] = 250

    pitch_dir = os.path.join(tex_root, "pitch_clay")
    for fname, arr in [
        ("albedo.png", pitch_albedo_u8),
        ("normal.png", pitch_norm_u8),
        ("roughness.png", pitch_rough_u8),
    ]:
        p = os.path.join(pitch_dir, fname)
        sz = write_png_rgb_or_gray(p, arr)
        written[f"pitch_clay/{fname}"] = {"path": p, "size_bytes": sz, "resolution": "2048x512"}

    # --------------------------------------------------------------------------
    # C. PERIMETER ADVERTISING RIBBON TEXTURE (2048x256, UV0 MAPPED)
    # --------------------------------------------------------------------------
    aw, ah = 2048, 256
    ad_rgb = np.zeros((ah, aw, 3), dtype=np.uint8)
    # Alternating bold sponsor panels along U (Royal Blue, Stadium Orange, Deep Navy, Gold)
    panel_colors = [
        (12, 58, 178),
        (232, 82, 14),
        (10, 28, 86),
        (235, 178, 16),
        (16, 118, 198),
        (196, 28, 44),
        (14, 46, 142),
        (240, 124, 12),
    ]
    panel_w = aw // len(panel_colors)
    for idx, col in enumerate(panel_colors):
        x0 = idx * panel_w
        x1 = (idx + 1) * panel_w if idx < len(panel_colors) - 1 else aw
        ad_rgb[:, x0:x1, 0] = col[0]
        ad_rgb[:, x0:x1, 1] = col[1]
        ad_rgb[:, x0:x1, 2] = col[2]
        # Crisp white/gold graphic bars inside each sponsor panel
        ad_rgb[28:56, x0 + 28 : x1 - 28] = (248, 248, 250)
        ad_rgb[84:172, x0 + 42 : x1 - 42] = (250, 250, 252)
        ad_rgb[196:222, x0 + 28 : x1 - 28] = (245, 202, 38)
        # Vertical divider
        ad_rgb[:, x0 : x0 + 6] = (20, 22, 28)

    # Top and bottom LED bezel trim
    ad_rgb[0:14, :, :] = (24, 26, 32)
    ad_rgb[ah - 14 : ah, :, :] = (24, 26, 32)
    ad_path = os.path.join(tex_root, "ad_boards", "albedo.png")
    sz_ad = write_png_rgb_or_gray(ad_path, ad_rgb)
    written["ad_boards/albedo.png"] = {"path": ad_path, "size_bytes": sz_ad, "resolution": "2048x256"}

    # --------------------------------------------------------------------------
    # D. 8K SCOREBOARD & CORNER LED SCREEN CANVAS TEXTURE (1024x512, UV0 MAPPED)
    # --------------------------------------------------------------------------
    sw, sh = 1024, 512
    sc_rgb = np.zeros((sh, sw, 3), dtype=np.uint8)
    # Deep broadcast navy background
    sc_rgb[:, :] = (10, 22, 54)
    # Top header banner (Stadium Orange & Gold)
    sc_rgb[24:96, 24 : sw - 24] = (228, 78, 14)
    sc_rgb[96:108, 24 : sw - 24] = (245, 192, 24)
    # Scoreboard main team total box (Royal Blue)
    sc_rgb[128:320, 36:620] = (18, 56, 142)
    # Bright white & gold score digit blocks
    sc_rgb[156:220, 64:380] = (248, 250, 255)
    sc_rgb[156:220, 410:590] = (250, 204, 32)
    sc_rgb[244:292, 64:590] = (196, 224, 255)
    # Right-side live replay / batter stats split screen
    sc_rgb[128:460, 644 : sw - 36] = (24, 92, 52)
    sc_rgb[148:290, 664 : sw - 56] = (46, 136, 68)
    sc_rgb[312:440, 664 : sw - 56] = (16, 40, 96)
    # Bottom match ticker bar
    sc_rgb[344:460, 36:620] = (14, 36, 88)
    sc_rgb[368:432, 64:590] = (245, 192, 24)

    sc_path = os.path.join(tex_root, "screens", "scoreboard_albedo.png")
    sz_sc = write_png_rgb_or_gray(sc_path, sc_rgb)
    written["screens/scoreboard_albedo.png"] = {"path": sc_path, "size_bytes": sz_sc, "resolution": "1024x512"}

    log(f"Baked all Milestone 3 2K PBR textures in {time.time() - t0:.2f}s")
    return written


