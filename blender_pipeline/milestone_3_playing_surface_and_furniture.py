# 4. CROWNED OUTFIELD TURF, FLUSH 22-YARD PITCH, STUMPS, BAILS & 30-YD CIRCLE
# ==============================================================================
def field_crown_z(x: float, y: float, config: dict) -> float:
    """
    Smooth drainage crown across the outfield:
    - Flat crown plateau z = 0.260 m across the central pitch table (|x| <= 11.20 m, |y| <= 1.525 m)
    - Smoothly tapers down to z = 0.00 m at the perimeter apron (rx = 77.5 m, ry = 71.5 m).
    """
    rx = config["outfield_rx"]
    ry = config["outfield_ry"]
    crown_h = config["crown_height"]

    # Distance outside the flat pitch table
    dx = max(0.0, abs(x) - 11.20) / (rx - 11.20)
    dy = max(0.0, abs(y) - 1.525) / (ry - 1.525)
    r2 = min(1.0, dx * dx + dy * dy)
    return crown_h * (1.0 - r2)


def build_crowned_outfield_and_pitch(config: dict, cols: dict, mats: dict) -> list:
    """
    Builds:
    1. `OUTFIELD_CROWNED_TURF`: Structured 2D rectilinear grid clipped to the
       stadium apron ellipse with an exact central rectangular cutout for the
       22-yard pitch strip. Zero polar rings = zero concentric ripple artifacts!
    2. `PITCH_CLAY_22YD`: 22.40 m x 3.05 m clay bed along X axis with 22-yard
       (20.12 m) bowling creases, popping creases, and return creases, sharing
       exact z = 0.260 m elevation at the turf cutout border (zero z-fighting).
    3. `PITCH_STUMPS_AND_BAILS`: 6 ash-wood stumps + 4 bails at x = +/-10.06 m.
    4. `FIELD_30YD_CIRCLE_DECAL`: Dashed white 30-yard oval conforming to the crown.
    """
    log("Building crowned quad-grid outfield turf, flush 22-yard pitch strip, stumps/bails, and 30-yard circle...")
    rx_max = config["outfield_rx"]
    ry_max = config["outfield_ry"]
    p_half_x = config["pitch_bed_length"] * 0.5   # 11.20 m
    p_half_y = config["pitch_width"] * 0.5        # 1.525 m

    # Build grid coordinate arrays that include the exact pitch cutout borders (+/-11.20, +/-1.525)
    xs = sorted(set(list(np.linspace(-rx_max, rx_max, 112)) + [-p_half_x, p_half_x]))
    ys = sorted(set(list(np.linspace(-ry_max, ry_max, 104)) + [-p_half_y, p_half_y]))

    bm_turf = bmesh.new()
    uv_turf = bm_turf.loops.layers.uv.new("UVMap")

    nx = len(xs) - 1
    ny = len(ys) - 1
    v_grid = [[None] * (nx + 1) for _ in range(ny + 1)]

    for iy, y in enumerate(ys):
        for ix, x in enumerate(xs):
            # Clamp points slightly outside the ellipse onto the elliptical apron rim
            ell_r = math.hypot(x / rx_max, y / ry_max)
            if ell_r > 1.0:
                px = x / ell_r
                py = y / ell_r
            else:
                px, py = x, y
            pz = field_crown_z(px, py, config)
            v_grid[iy][ix] = (bm_turf.verts.new((px, py, pz)), ell_r, px, py)

    for iy in range(ny):
        y_mid = 0.5 * (ys[iy] + ys[iy + 1])
        for ix in range(nx):
            x_mid = 0.5 * (xs[ix] + xs[ix + 1])
            # Skip cells inside the 22-yard pitch bed cutout so pitch & turf never overlap!
            if (abs(x_mid) < p_half_x - 1e-4) and (abs(y_mid) < p_half_y - 1e-4):
                continue

            v00, r00, x00, y00 = v_grid[iy][ix]
            v10, r10, x10, y10 = v_grid[iy][ix + 1]
            v11, r11, x11, y11 = v_grid[iy + 1][ix + 1]
            v01, r01, x01, y01 = v_grid[iy + 1][ix]

            if min(r00, r10, r11, r01) > 1.03:
                continue

            try:
                f = bm_turf.faces.new((v00, v10, v11, v01))
                for loop, (vx, vy) in zip(f.loops, [(x00, y00), (x10, y10), (x11, y11), (x01, y01)]):
                    loop[uv_turf].uv = ((vx + 80.0) / 160.0, (vy + 80.0) / 160.0)
            except ValueError:
                pass

    bmesh.ops.remove_doubles(bm_turf, verts=bm_turf.verts, dist=0.001)
    bmesh.ops.recalc_face_normals(bm_turf, faces=bm_turf.faces)
    mesh_turf = bpy.data.meshes.new("OUTFIELD_CROWNED_TURF_MESH")
    bm_turf.to_mesh(mesh_turf)
    bm_turf.free()
    for p in mesh_turf.polygons:
        p.use_smooth = True
    mesh_turf.update()
    turf_obj = bpy.data.objects.new("OUTFIELD_CROWNED_TURF", mesh_turf)
    turf_obj.data.materials.append(mats["outfield_turf"])
    cols["PLAYING_SURFACE"].objects.link(turf_obj)

    # --- 2. Flush 22-Yard Pitch Strip (subdivided grid in exact cutout) ---
    bm_pitch = bmesh.new()
    uv_pitch = bm_pitch.loops.layers.uv.new("UVMap")
    px_list = np.linspace(-p_half_x, p_half_x, 33)
    py_list = np.linspace(-p_half_y, p_half_y, 9)
    pv_grid = [[None] * len(px_list) for _ in range(len(py_list))]
    z_pitch = config["crown_height"]

    for iy, y in enumerate(py_list):
        for ix, x in enumerate(px_list):
            pv_grid[iy][ix] = bm_pitch.verts.new((float(x), float(y), z_pitch))

    for iy in range(len(py_list) - 1):
        v0 = iy / float(len(py_list) - 1)
        v1 = (iy + 1) / float(len(py_list) - 1)
        for ix in range(len(px_list) - 1):
            u0 = ix / float(len(px_list) - 1)
            u1 = (ix + 1) / float(len(px_list) - 1)
            f = bm_pitch.faces.new((pv_grid[iy][ix], pv_grid[iy][ix + 1], pv_grid[iy + 1][ix + 1], pv_grid[iy + 1][ix]))
            for loop, uv in zip(f.loops, [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]):
                loop[uv_pitch].uv = uv

    bmesh.ops.recalc_face_normals(bm_pitch, faces=bm_pitch.faces)
    mesh_pitch = bpy.data.meshes.new("PITCH_CLAY_22YD_MESH")
    bm_pitch.to_mesh(mesh_pitch)
    bm_pitch.free()
    for p in mesh_pitch.polygons:
        p.use_smooth = True
    mesh_pitch.update()
    pitch_obj = bpy.data.objects.new("PITCH_CLAY_22YD", mesh_pitch)
    pitch_obj.data.materials.append(mats["pitch_clay"])
    cols["PLAYING_SURFACE"].objects.link(pitch_obj)

    # --- 3. Stumps & Bails at Both Ends of the 22-Yard Pitch (x = +/-10.06 m) ---
    bm_stumps = bmesh.new()
    uv_stumps = bm_stumps.loops.layers.uv.new("UVMap")
    stump_h = 0.711  # 28 inches
    stump_r = 0.019  # 3.8 cm diameter
    stump_ys = (-0.1143, 0.0, 0.1143)  # 9 inches total width

    for end_x in (-10.06, 10.06):
        for sy in stump_ys:
            # Main wooden stump cylinder
            res_s = bmesh.ops.create_cone(
                bm_stumps,
                cap_ends=True,
                cap_tris=False,
                segments=14,
                radius1=stump_r,
                radius2=stump_r * 0.94,
                depth=stump_h,
                matrix=Matrix.Translation((end_x, sy, z_pitch + stump_h * 0.5)),
            )
            for v in res_s["verts"]:
                for f in v.link_faces:
                    f.material_index = 0
            # Glowing LED bail-groove collar at top of stump
            res_top = bmesh.ops.create_cone(
                bm_stumps,
                cap_ends=True,
                cap_tris=False,
                segments=14,
                radius1=stump_r * 0.92,
                radius2=stump_r * 0.75,
                depth=0.024,
                matrix=Matrix.Translation((end_x, sy, z_pitch + stump_h + 0.012)),
            )
            for v in res_top["verts"]:
                for f in v.link_faces:
                    f.material_index = 1

        # 2 Bails spanning between (-0.1143..0.0) and (0.0..+0.1143)
        for by_mid in (-0.05715, 0.05715):
            # Bail central barrel (aligned along Y)
            res_bail = bmesh.ops.create_cone(
                bm_stumps,
                cap_ends=True,
                cap_tris=False,
                segments=12,
                radius1=0.010,
                radius2=0.010,
                depth=0.108,
                matrix=Matrix.Translation((end_x, by_mid, z_pitch + stump_h + 0.028)) @ Matrix.Rotation(math.pi * 0.5, 4, "X"),
            )
            for v in res_bail["verts"]:
                for f in v.link_faces:
                    f.material_index = 0

    for f in bm_stumps.faces:
        for loop in f.loops:
            loop[uv_stumps].uv = (0.5, 0.5)
    bmesh.ops.recalc_face_normals(bm_stumps, faces=bm_stumps.faces)
    mesh_stumps = bpy.data.meshes.new("PITCH_STUMPS_AND_BAILS_MESH")
    bm_stumps.to_mesh(mesh_stumps)
    bm_stumps.free()
    for p in mesh_stumps.polygons:
        p.use_smooth = True
    stumps_obj = bpy.data.objects.new("PITCH_STUMPS_AND_BAILS", mesh_stumps)
    stumps_obj.data.materials.append(mats["ash_wood_stumps"])
    stumps_obj.data.materials.append(mats["stump_led_zing"])
    cols["PLAYING_SURFACE"].objects.link(stumps_obj)

    # --- 4. Dashed 30-Yard Fielding Restriction Circle Decal ---
    bm_circle = bmesh.new()
    uv_circle = bm_circle.loops.layers.uv.new("UVMap")
    r_30 = config["circle_30yd_radius"]
    w_x = 10.06

    # Generate perimeter path points of standard ICC 30-yard oval:
    # Two semicircles of radius 27.432 m centered at (+10.06, 0) and (-10.06, 0) + straight segments
    path_pts = []
    for k in range(36):
        ang = -math.pi * 0.5 + (math.pi * k) / 36.0
        path_pts.append((w_x + r_30 * math.cos(ang), r_30 * math.sin(ang)))
    for k in range(12):
        frac = k / 12.0
        path_pts.append((w_x - 2.0 * w_x * frac, r_30))
    for k in range(36):
        ang = math.pi * 0.5 + (math.pi * k) / 36.0
        path_pts.append((-w_x + r_30 * math.cos(ang), r_30 * math.sin(ang)))
    for k in range(12):
        frac = k / 12.0
        path_pts.append((-w_x + 2.0 * w_x * frac, -r_30))

    n_pts = len(path_pts)
    dash_half_w = 0.11  # 22 cm wide painted white dash
    for i in range(0, n_pts, 2):
        p0 = Vector((path_pts[i][0], path_pts[i][1], 0.0))
        p1 = Vector((path_pts[(i + 1) % n_pts][0], path_pts[(i + 1) % n_pts][1], 0.0))
        tang = (p1 - p0).normalized()
        perp = Vector((-tang.y, tang.x, 0.0)) * dash_half_w
        c0 = p0 + perp
        c1 = p0 - perp
        c2 = p1 - perp
        c3 = p1 + perp
        verts = [
            bm_circle.verts.new((c.x, c.y, field_crown_z(c.x, c.y, config) + 0.008))
            for c in (c0, c1, c2, c3)
        ]
        f = bm_circle.faces.new(verts)
        for loop in f.loops:
            loop[uv_circle].uv = (0.5, 0.5)

    bmesh.ops.recalc_face_normals(bm_circle, faces=bm_circle.faces)
    mesh_circle = bpy.data.meshes.new("FIELD_30YD_CIRCLE_DECAL_MESH")
    bm_circle.to_mesh(mesh_circle)
    bm_circle.free()
    circle_obj = bpy.data.objects.new("FIELD_30YD_CIRCLE_DECAL", mesh_circle)
    circle_obj.data.materials.append(mats["white_decal"])
    cols["PLAYING_SURFACE"].objects.link(circle_obj)

    return [turf_obj, pitch_obj, stumps_obj, circle_obj]


