# 5. PADDED BOUNDARY ROPE & UV0 PERIMETER ADVERTISING BOARD RING
# ==============================================================================
def build_boundary_and_ad_boards(config: dict, cols: dict, mats: dict) -> list:
    log("Building padded boundary cushion rope and UV0-mapped perimeter LED advertising ring...")
    rx_b = config["boundary_rx"]
    ry_b = config["boundary_ry"]
    segs = 144

    # 1. Padded Boundary Rope (triangular prism cushion along the boundary ellipse)
    bm_rope = bmesh.new()
    uv_rope = bm_rope.loops.layers.uv.new("UVMap")
    rope_r = 0.16

    for i in range(segs):
        a0 = (2.0 * math.pi * i) / float(segs)
        a1 = (2.0 * math.pi * (i + 1)) / float(segs)
        x0, y0 = rx_b * math.cos(a0), ry_b * math.sin(a0)
        x1, y1 = rx_b * math.cos(a1), ry_b * math.sin(a1)
        z0 = field_crown_z(x0, y0, config)
        z1 = field_crown_z(x1, y1, config)

        n0 = Vector((math.cos(a0), math.sin(a0), 0.0))
        n1 = Vector((math.cos(a1), math.sin(a1), 0.0))

        # Triangular padded cushion cross-section: inner base, outer base, top ridge
        v0_in = bm_rope.verts.new((x0 - n0.x * rope_r, y0 - n0.y * rope_r, z0 + 0.01))
        v0_out = bm_rope.verts.new((x0 + n0.x * rope_r, y0 + n0.y * rope_r, z0 + 0.01))
        v0_top = bm_rope.verts.new((x0, y0, z0 + 0.24))

        v1_in = bm_rope.verts.new((x1 - n1.x * rope_r, y1 - n1.y * rope_r, z1 + 0.01))
        v1_out = bm_rope.verts.new((x1 + n1.x * rope_r, y1 + n1.y * rope_r, z1 + 0.01))
        v1_top = bm_rope.verts.new((x1, y1, z1 + 0.24))

        mat_idx = 0 if (i % 4 < 3) else 1
