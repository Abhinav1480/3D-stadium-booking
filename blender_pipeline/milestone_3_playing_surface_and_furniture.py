# 7. SIX 62m TAPERED STEEL LATTICE FLOODLIGHT TOWERS WITH 96 EMISSIVE LAMPS EACH
# ==============================================================================
def build_six_floodlight_towers(config: dict, cols: dict, mats: dict) -> list:
    """
    Builds 6 monumental 62.0 m tall tapered steel lattice floodlight towers
    (`FLOODLIGHT_TOWER_01`..`06`). Each tower features:
    - 4 tapered corner steel legs (4.8m x 4.8m base -> 2.2m x 2.2m top neck)
    - 14 horizontal diaphragm lacing rings + X-bracing diagonals on all 4 faces
    - Maintenance ladder & upper service catwalk at z = 53.5 m
    - Tilted head frame (13.6 m wide x 8.6 m tall) aimed at pitch centre (0,0,0)
    - 96 individual floodlight lamp units (8 rows x 12 cols) with separate material
      slots for the dark aluminum housings and two emissive lamp banks!
    """
    log("Building 6 tapered 62 m steel lattice floodlight towers (96 individual emissive lamps per tower)...")
    h_total = config["floodlight_height"]  # 62.0 m
    neck_z = h_total - 8.5                 # 53.5 m
    rx_t = config["floodlight_rx"]
    ry_t = config["floodlight_ry"]
    angles = config["floodlight_angles_deg"]

    def add_bar(bm, p0: Vector, p1: Vector, radius: float, mat_idx: int = 0, segs: int = 6):
        vec = p1 - p0
        length = vec.length
        if length < 0.01:
            return
        mid = (p0 + p1) * 0.5
        rot = Vector((0, 0, 1)).rotation_difference(vec.normalized()).to_matrix().to_4x4()
        res = bmesh.ops.create_cone(
            bm,
            cap_ends=True,
            cap_tris=False,
            segments=segs,
            radius1=radius,
            radius2=radius,
            depth=length,
            matrix=Matrix.Translation(mid) @ rot,
        )
        for v in res["verts"]:
            for f in v.link_faces:
                f.material_index = mat_idx

    bm_master = bmesh.new()
    n_bays = 14
    w_base = 2.45
    w_neck = 1.10

    bay_nodes = []
    for b in range(n_bays + 1):
        frac = b / float(n_bays)
        z = frac * neck_z
        hw = w_base + (w_neck - w_base) * (frac ** 0.85)
        lean_x = (frac ** 2.0) * 2.2
        corners = [
            Vector((lean_x - hw, -hw, z)),
            Vector((lean_x + hw, -hw, z)),
            Vector((lean_x + hw,  hw, z)),
            Vector((lean_x - hw,  hw, z)),
        ]
        bay_nodes.append(corners)

    for b in range(n_bays):
        c_bot = bay_nodes[b]
        c_top = bay_nodes[b + 1]
        for k in range(4):
            kn = (k + 1) % 4
            add_bar(bm_master, c_bot[k], c_top[k], radius=0.18, mat_idx=0, segs=8)
            add_bar(bm_master, c_top[k], c_top[kn], radius=0.10, mat_idx=0, segs=6)
            add_bar(bm_master, c_bot[k], c_top[kn], radius=0.075, mat_idx=0, segs=6)
            add_bar(bm_master, c_bot[kn], c_top[k], radius=0.075, mat_idx=0, segs=6)

    res_plinth = bmesh.ops.create_cube(
        bm_master,
        size=1.0,
        matrix=Matrix.Translation((0.0, 0.0, 0.7)) @ Matrix.Diagonal((5.8, 5.8, 1.4, 1.0)),
    )
    for v in res_plinth["verts"]:
        for f in v.link_faces:
            f.material_index = 0

    res_plat = bmesh.ops.create_cube(
        bm_master,
        size=1.0,
        matrix=Matrix.Translation((2.2, 0.0, neck_z)) @ Matrix.Diagonal((3.6, 14.2, 0.35, 1.0)),
    )
    for v in res_plat["verts"]:
        for f in v.link_faces:
            f.material_index = 0

    head_center = Vector((2.8, 0.0, neck_z + 4.4))
    tilt_rad = math.radians(24.0)
    head_rot = Matrix.Rotation(tilt_rad, 4, "Y")
    head_xform = Matrix.Translation(head_center) @ head_rot

    lamp_rows = 8
    lamp_cols = 12
    frame_w = 13.4
    frame_h = 8.2

    for r_i in range(lamp_rows + 1):
        lz = -frame_h * 0.5 + (r_i / float(lamp_rows)) * frame_h
        p_l = head_xform @ Vector((0.0, -frame_w * 0.5, lz))
        p_r = head_xform @ Vector((0.0,  frame_w * 0.5, lz))
        add_bar(bm_master, p_l, p_r, radius=0.08, mat_idx=0, segs=6)

    for c_i in range(lamp_cols + 1):
        ly = -frame_w * 0.5 + (c_i / float(lamp_cols)) * frame_w
        p_b = head_xform @ Vector((0.0, ly, -frame_h * 0.5))
        p_t = head_xform @ Vector((0.0, ly,  frame_h * 0.5))
        add_bar(bm_master, p_b, p_t, radius=0.075, mat_idx=0, segs=6)

    for r_i in range(lamp_rows):
        lz = -frame_h * 0.5 + ((r_i + 0.5) / float(lamp_rows)) * frame_h
        for c_i in range(lamp_cols):
            ly = -frame_w * 0.5 + ((c_i + 0.5) / float(lamp_cols)) * frame_w
            lamp_local = Vector((0.22, ly, lz))
            lamp_mat = head_xform @ Matrix.Translation(lamp_local)

            res_housing = bmesh.ops.create_cube(
                bm_master,
                size=1.0,
                matrix=lamp_mat @ Matrix.Diagonal((0.36, 0.78, 0.64, 1.0)),
            )
            for v in res_housing["verts"]:
                for f in v.link_faces:
                    f.material_index = 1

            emissive_slot = 2 if ((r_i + c_i) % 2 == 0) else 3
            res_lens = bmesh.ops.create_cube(
                bm_master,
                size=1.0,
                matrix=lamp_mat @ Matrix.Translation((0.18, 0.0, 0.0)) @ Matrix.Diagonal((0.06, 0.68, 0.54, 1.0)),
            )
            for v in res_lens["verts"]:
                for f in v.link_faces:
                    f.material_index = emissive_slot

    uv_m = bm_master.loops.layers.uv.new("UVMap")
    for f in bm_master.faces:
        for loop in f.loops:
            loop[uv_m].uv = (0.5, 0.5)
    bmesh.ops.recalc_face_normals(bm_master, faces=bm_master.faces)

    master_tower_mesh = bpy.data.meshes.new("FLOODLIGHT_TOWER_MASTER_MESH")
    bm_master.to_mesh(master_tower_mesh)
    bm_master.free()
    master_tower_mesh.materials.append(mats["floodlight_steel"])       # slot 0
    master_tower_mesh.materials.append(mats["floodlight_housing"])     # slot 1
    master_tower_mesh.materials.append(mats["floodlight_emissive_a"])  # slot 2
    master_tower_mesh.materials.append(mats["floodlight_emissive_b"])  # slot 3

    floodlight_hooks = []
    for idx, ang_deg in enumerate(angles, start=1):
        theta = math.radians(ang_deg)
        tx = rx_t * math.cos(theta)
        ty = ry_t * math.sin(theta)
        yaw = math.atan2(-ty, -tx)

        t_obj = bpy.data.objects.new(f"FLOODLIGHT_TOWER_{idx:02d}", master_tower_mesh)
        t_obj.matrix_world = Matrix.Translation((tx, ty, 0.0)) @ Matrix.Rotation(yaw, 4, "Z")
        cols["FLOODLIGHT_TOWERS"].objects.link(t_obj)

        head_world = t_obj.matrix_world @ head_center
        floodlight_hooks.append((f"FLOODLIGHT_{idx:02d}", head_world, yaw))

    log(f"Built 6 floodlight towers ({len(master_tower_mesh.polygons):,} tris per tower, 96 lamps/tower)")
    return floodlight_hooks


# ==============================================================================
# 8. CREATE FIXED-NAME RUNTIME EMPTIES (`CAMERA_PITCH_CENTRE`, `SCOREBOARD_01..02`,
#    `LED_SCREEN_01..02`, `FLOODLIGHT_01..06`)
# ==============================================================================
def create_fixed_name_empties(cols: dict, furniture_info: dict, floodlight_hooks: list) -> list:
    log("Creating fixed-name runtime empties (CAMERA_PITCH_CENTRE, SCOREBOARD_01..02, LED_SCREEN_01..02, FLOODLIGHT_01..06)...")
    emp_col = cols["RUNTIME_HOOK_EMPTIES"]
    created_names = []

    def add_empty(name: str, loc: Vector, target: Vector = Vector((0.0, 0.0, 0.26))) -> bpy.types.Object:
        existing = bpy.data.objects.get(name)
        if existing is not None:
            bpy.data.objects.remove(existing, do_unlink=True)
        emp = bpy.data.objects.new(name, None)
        emp.empty_display_type = "ARROWS"
        emp.empty_display_size = 2.5
        emp.location = Vector(loc)
        vec = Vector(target) - emp.location
        if vec.length > 0.001:
            emp.rotation_euler = vec.to_track_quat("-Z", "Y").to_euler()
        emp_col.objects.link(emp)
        created_names.append(name)
        return emp

    add_empty("CAMERA_PITCH_CENTRE", Vector((0.0, 0.0, 1.65)), target=Vector((10.06, 0.0, 1.20)))

    for sb_name, pos, _ in furniture_info["scoreboard_hooks"]:
        add_empty(sb_name, pos, target=Vector((0.0, 0.0, 0.26)))

    for led_name, pos, _ in furniture_info["led_screen_hooks"]:
        add_empty(led_name, pos, target=Vector((0.0, 0.0, 0.26)))

    for fl_name, pos, _ in floodlight_hooks:
        add_empty(fl_name, pos, target=Vector((0.0, 0.0, 0.26)))

    log(f"Created {len(created_names)} fixed-name empties: {', '.join(created_names)}")
    return created_names


