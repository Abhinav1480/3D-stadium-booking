# 4. VIP HOSPITALITY CURTAIN WALL, EXTERIOR COLONNADE PILLARS & CONCOURSE SLABS
# ==============================================================================
def build_vip_and_exterior_structure(config: dict, cols: dict, mats: dict) -> list:
    """
    Generates:
    1. `VIP_HOSPITALITY_CURTAIN_WALL`: Reflective floor-to-ceiling glass suites and
       warm illuminated lounge soffits between Tier 2 and Tier 3.
    2. `EXTERIOR_STRUCTURAL_COLONNADE`: 48 tapered A-frame perimeter super-columns,
       radial raker beams, 3 elevated concourse slabs, and an inner concourse
       shadow-enclosure drum wall so daylight never leaks unnaturally through the stands.
    """
    log("Building VIP hospitality curtain wall, 48 exterior super-columns, and concourse slabs...")
    bm_vip = bmesh.new()
    uv_vip = bm_vip.loops.layers.uv.new("UVMap")
    vip_mats = [mats["curtain_glass"], mats["vip_glow"], mats["dark_steel"]]

    bm_struct = bmesh.new()
    uv_struct = bm_struct.loops.layers.uv.new("UVMap")
    struct_mats = [mats["concrete_structural"], mats["concrete_risers"], mats["dark_steel"]]

    def add_quad(bm, uv_layer, p0, p1, p2, p3, mat_idx=0):
        v0 = bm.verts.new(p0)
        v1 = bm.verts.new(p1)
        v2 = bm.verts.new(p2)
        v3 = bm.verts.new(p3)
        f = bm.faces.new((v0, v1, v2, v3))
        f.material_index = mat_idx
        for loop, uv in zip(f.loops, [(0, 0), (1, 0), (1, 1), (0, 1)]):
            loop[uv_layer].uv = uv

    # 1. VIP Glass Curtain Wall Ring (at back of Tier 2: rx=103.5m, ry=97.5m, z=17.0..20.8m)
    vip_rx, vip_ry = 103.2, 97.2
    vip_z0, vip_z1 = 17.0, 20.8
    segs = 96
    for i in range(segs):
        a0 = (2.0 * math.pi * i) / float(segs)
        a1 = (2.0 * math.pi * (i + 1)) / float(segs)
        c0, s0 = math.cos(a0), math.sin(a0)
        c1, s1 = math.cos(a1), math.sin(a1)

        # Inclined curtain glass panel
        add_quad(
            bm_vip, uv_vip,
            (vip_rx * c0, vip_ry * s0, vip_z0),
            (vip_rx * c1, vip_ry * s1, vip_z0),
            ((vip_rx - 0.8) * c1, (vip_ry - 0.8) * s1, vip_z1),
            ((vip_rx - 0.8) * c0, (vip_ry - 0.8) * s0, vip_z1),
            mat_idx=0,
        )
        # Warm glowing interior ceiling soffit behind glass
        add_quad(
            bm_vip, uv_vip,
            ((vip_rx - 0.5) * c0, (vip_ry - 0.5) * s0, vip_z1 - 0.25),
            ((vip_rx - 0.5) * c1, (vip_ry - 0.5) * s1, vip_z1 - 0.25),
            ((vip_rx + 4.5) * c1, (vip_ry + 4.5) * s1, vip_z1 - 0.25),
            ((vip_rx + 4.5) * c0, (vip_ry + 4.5) * s0, vip_z1 - 0.25),
            mat_idx=1,
        )

    # 2. Inner Concourse Shadow-Enclosure Drum Walls behind Tier 1 (r=96m, z=0..12.5m)
    #    and behind Tier 3 (r=122m, z=20..36.2m) so no back-sky light leaks through stands
    for wall_rx, wall_ry, wz0, wz1 in [
        (96.0, 90.0, 0.0, 12.2),
        (105.0, 99.0, 11.5, 22.0),
        (122.0, 116.0, 21.0, 36.2),
    ]:
        for i in range(segs):
            a0 = (2.0 * math.pi * i) / float(segs)
            a1 = (2.0 * math.pi * (i + 1)) / float(segs)
            c0, s0 = math.cos(a0), math.sin(a0)
            c1, s1 = math.cos(a1), math.sin(a1)
            add_quad(
                bm_struct, uv_struct,
                (wall_rx * c0, wall_ry * s0, wz0),
                (wall_rx * c1, wall_ry * s1, wz0),
                (wall_rx * c1, wall_ry * s1, wz1),
                (wall_rx * c0, wall_ry * s0, wz1),
                mat_idx=1,
            )

    # 3. Multi-level Concourse Ring Slabs & 48 Exterior Tapered Super-Columns
    num_cols = config["roof"]["num_bays"]
    col_rx = config["roof"]["outer_rx"] - 2.0
    col_ry = config["roof"]["outer_ry"] - 2.0
    eave_z = config["roof"]["eave_z"]

    # Concourse slabs at z = 0.0 (plinth), 7.5m, 15.5m, 23.5m
    for slab_z, slab_in_off, slab_out_off in [
        (0.25, -32.0, 14.0),
        (7.50, -24.0, 2.5),
        (15.50, -18.0, 2.0),
        (23.50, -12.0, 1.5),
    ]:
        in_rx, in_ry = col_rx + slab_in_off, col_ry + slab_in_off
        out_rx, out_ry = col_rx + slab_out_off, col_ry + slab_out_off
        for i in range(segs):
            a0 = (2.0 * math.pi * i) / float(segs)
            a1 = (2.0 * math.pi * (i + 1)) / float(segs)
            c0, s0 = math.cos(a0), math.sin(a0)
            c1, s1 = math.cos(a1), math.sin(a1)
            add_quad(
                bm_struct, uv_struct,
                (in_rx * c0, in_ry * s0, slab_z),
                (in_rx * c1, in_ry * s1, slab_z),
                (out_rx * c1, out_ry * s1, slab_z),
                (out_rx * c0, out_ry * s0, slab_z),
                mat_idx=0,
            )
            # Outer slab fascia edge (0.65m thick)
            add_quad(
                bm_struct, uv_struct,
                (out_rx * c0, out_ry * s0, slab_z - 0.65),
                (out_rx * c1, out_ry * s1, slab_z - 0.65),
                (out_rx * c1, out_ry * s1, slab_z),
                (out_rx * c0, out_ry * s0, slab_z),
                mat_idx=1,
            )

    # 48 Tapered Architectural Piers + Diagonal Raker Struts around the perimeter
    for i in range(num_cols):
        theta = (2.0 * math.pi * i) / float(num_cols)
        ct, st = math.cos(theta), math.sin(theta)
        rot_z = Matrix.Rotation(theta, 4, "Z")

        # Main vertical tapered pier at (col_rx, col_ry)
        pier_pos = Vector((col_rx * ct, col_ry * st, eave_z * 0.5))
        mat_pier = Matrix.Translation(pier_pos) @ rot_z @ Matrix.Diagonal((2.2, 0.95, eave_z, 1.0))
        res = bmesh.ops.create_cube(bm_struct, size=1.0, matrix=mat_pier)
        for v in res["verts"]:
            for f in v.link_faces:
                f.material_index = 0

        # Inward-sloping raker column supporting the upper bowl
        raker_p0 = Vector(((col_rx - 18.0) * ct, (col_ry - 18.0) * st, 0.0))
        raker_p1 = Vector(((col_rx - 2.0) * ct, (col_ry - 2.0) * st, 31.5))
        raker_vec = raker_p1 - raker_p0
        raker_mid = (raker_p0 + raker_p1) * 0.5
        rot_raker = Vector((0, 0, 1)).rotation_difference(raker_vec.normalized()).to_matrix().to_4x4()
        mat_raker = Matrix.Translation(raker_mid) @ rot_raker @ Matrix.Diagonal((1.4, 0.85, raker_vec.length, 1.0))
        res_r = bmesh.ops.create_cube(bm_struct, size=1.0, matrix=mat_raker)
        for v in res_r["verts"]:
            for f in v.link_faces:
                f.material_index = 1

    vip_obj = finalize_mesh("VIP_HOSPITALITY_CURTAIN_WALL", bm_vip, cols["VIP_AND_STRUCTURE"], vip_mats, smooth=False)
    struct_obj = finalize_mesh("EXTERIOR_STRUCTURAL_COLONNADE", bm_struct, cols["VIP_AND_STRUCTURE"], struct_mats, smooth=False)
    log(f"Built VIP_HOSPITALITY_CURTAIN_WALL & EXTERIOR_STRUCTURAL_COLONNADE ({len(struct_obj.data.polygons)} faces)")
    return [vip_obj, struct_obj]


