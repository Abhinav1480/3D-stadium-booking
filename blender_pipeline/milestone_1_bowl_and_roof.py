def setup_lighting_and_cameras(config: dict, cols: dict) -> dict:
    log("Configuring physical Nishita Sky / Sun lighting and 3 inspection cameras...")
    scene = bpy.context.scene

    # World shader with physical Sky Texture calibrated to natural exposure
    world = bpy.data.worlds.new("STADIUMX_Physical_Sky")
    scene.world = world
    world.use_nodes = True
    nt = world.node_tree
    nodes = nt.nodes
    links = nt.links
    nodes.clear()

    bg = nodes.new("ShaderNodeBackground")
    bg.inputs["Strength"].default_value = 0.14  # Calibrated for Nishita physical sun/sky
    out = nodes.new("ShaderNodeOutputWorld")
    sky = nodes.new("ShaderNodeTexSky")
    sky.sky_type = "NISHITA"
    sky.sun_disc = True
    sky.sun_elevation = math.radians(32.0)
    sky.sun_rotation = math.radians(48.0)
    sky.air_density = 1.15
    sky.dust_density = 1.05
    links.new(sky.outputs["Color"], bg.inputs["Color"])
    links.new(bg.outputs["Background"], out.inputs["Surface"])

    # Filmic tone mapping for crisp architectural contrast without blown highlights
    scene.view_settings.view_transform = "Filmic"
    scene.view_settings.look = "Medium High Contrast"
    scene.view_settings.exposure = 0.0

    def make_camera(name: str, loc: tuple, target: tuple, lens_mm: float = 28.0) -> bpy.types.Object:
        cam_data = bpy.data.cameras.new(name)
        cam_data.lens = lens_mm
        cam_data.clip_start = 0.5
        cam_data.clip_end = 1500.0
        cam_obj = bpy.data.objects.new(name, cam_data)
        cam_obj.location = Vector(loc)
        direction = Vector(target) - cam_obj.location
        cam_obj.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()
        link_exclusively(cam_obj, cols["RENDER_CAMERAS"])
        return cam_obj

    cameras = {
        "view1_aerial_bowl": make_camera(
            "CAM_M1_Aerial_Overview",
            loc=(172.0, -152.0, 114.0),
            target=(0.0, 0.0, 10.0),
            lens_mm=30.0,
        ),
        "view2_interior_tiers": make_camera(
            "CAM_M1_Interior_Bowl_Tiers",
            loc=(-76.0, -38.0, 17.5),
            target=(65.0, 35.0, 18.0),
            lens_mm=24.0,
        ),
        "view3_roof_truss_detail": make_camera(
            "CAM_M1_Roof_Truss_Detail",
            loc=(0.0, -48.0, 16.0),
            target=(0.0, -96.0, 35.5),
            lens_mm=28.0,
        ),
    }
    return cameras


