# 5. CANTILEVERED SPACE-FRAME ROOF TRUSSES & PLEATED PTFE TENSION MEMBRANE
# ==============================================================================
def build_cantilevered_roof_structure(config: dict, cols: dict, mats: dict) -> list:
    """
    Builds the signature architectural roof of STADIUMX:
    1. `ROOF_SPACEFRAME_STEEL_TRUSSES`: 48 radial 3D boomerang trusses with upper
       and lower tubular steel chords, diagonal web Warren bracing, 6 concentric
       purlin rings, and a heavy inner ocular tension ring.
    2. `ROOF_PTFE_PLEATED_MEMBRANE`: 48 pleated catenary-arched tension fabric bays
       spanning between the radial trusses.
    """
    log("Building 48 radial 3D space-frame steel trusses and pleated PTFE roof canopy...")
    r_cfg = config["roof"]
    n_bays = r_cfg["num_bays"]
    in_rx, in_ry = r_cfg["inner_rx"], r_cfg["inner_ry"]
    out_rx, out_ry = r_cfg["outer_rx"], r_cfg["outer_ry"]
    eave_z = r_cfg["eave_z"]
    tip_z = r_cfg["inner_tip_z"]
    d_out = r_cfg["truss_depth_outer"]
    d_in = r_cfg["truss_depth_inner"]
    c_rad = r_cfg["chord_radius"]
    w_rad = r_cfg["web_radius"]
    n_purlins = r_cfg["purlin_rings"]

    bm_truss = bmesh.new()
    uv_truss = bm_truss.loops.layers.uv.new("UVMap")

    bm_membrane = bmesh.new()
    uv_membrane = bm_membrane.loops.layers.uv.new("UVMap")

    def add_steel_tube(bm, p0: Vector, p1: Vector, radius: float, segs: int = 8):
        vec = p1 - p0
        length = vec.length
        if length < 0.005:
            return
        mid = (p0 + p1) * 0.5
        rot = Vector((0, 0, 1)).rotation_difference(vec.normalized()).to_matrix().to_4x4()
        bmesh.ops.create_cone(
            bm,
            cap_ends=True,
            cap_tris=False,
            segments=segs,
            radius1=radius,
            radius2=radius,
            depth=length,
            matrix=Matrix.Translation(mid) @ rot,
        )

    def truss_node_points(theta: float, frac: float) -> tuple:
        rx = out_rx + (in_rx - out_rx) * frac
        ry = out_ry + (in_ry - out_ry) * frac
        arch_z = math.sin(frac * math.pi) * 1.85
        z_top = eave_z + (tip_z - eave_z) * frac + arch_z
        depth = d_out + (d_in - d_out) * (frac ** 0.75)
        z_bot = z_top - depth
        ct, st = math.cos(theta), math.sin(theta)
        return (
            Vector((rx * ct, ry * st, z_top)),
            Vector((rx * ct, ry * st, z_bot)),
        )

    # 1. Build 48 Radial Boomerang Space-Frame Trusses
    span_divs = 8
    for i in range(n_bays):
        theta = (2.0 * math.pi * i) / float(n_bays)
        top_pts = []
        bot_pts = []
        for k in range(span_divs + 1):
            frac = k / float(span_divs)
            pt_top, pt_bot = truss_node_points(theta, frac)
            top_pts.append(pt_top)
            bot_pts.append(pt_bot)

        for k in range(span_divs):
            add_steel_tube(bm_truss, top_pts[k], top_pts[k + 1], c_rad, segs=8)
            add_steel_tube(bm_truss, bot_pts[k], bot_pts[k + 1], c_rad * 0.9, segs=8)
            add_steel_tube(bm_truss, top_pts[k], bot_pts[k], w_rad, segs=6)
            if k % 2 == 0:
                add_steel_tube(bm_truss, top_pts[k], bot_pts[k + 1], w_rad, segs=6)
            else:
                add_steel_tube(bm_truss, bot_pts[k], top_pts[k + 1], w_rad, segs=6)
        add_steel_tube(bm_truss, top_pts[-1], bot_pts[-1], w_rad * 1.1, segs=6)

    # 2. Build Circumferential Purlin Rings & Inner Ocular Tension Ring
    for p_idx in range(n_purlins):
        frac = p_idx / float(n_purlins - 1)
        is_inner_ring = (p_idx == n_purlins - 1)
        is_outer_ring = (p_idx == 0)
        ring_rad = c_rad * 1.35 if (is_inner_ring or is_outer_ring) else w_rad * 1.15

        for i in range(n_bays):
            t0 = (2.0 * math.pi * i) / float(n_bays)
            t1 = (2.0 * math.pi * (i + 1)) / float(n_bays)
            top0, bot0 = truss_node_points(t0, frac)
            top1, bot1 = truss_node_points(t1, frac)
            add_steel_tube(bm_truss, top0, top1, ring_rad, segs=8)
            if is_inner_ring or is_outer_ring:
                add_steel_tube(bm_truss, bot0, bot1, ring_rad * 0.95, segs=8)
                add_steel_tube(bm_truss, top0, bot1, w_rad, segs=6)

    for f in bm_truss.faces:
        for loop in f.loops:
            loop[uv_truss].uv = (0.5, 0.5)

    # 3. Build 48 Pleated PTFE Tension Membrane Bays (with catenary sag/ridge pleats)
    sub_u = 4
    sub_v = 8
    for i in range(n_bays):
        t0 = (2.0 * math.pi * i) / float(n_bays)
        t1 = (2.0 * math.pi * (i + 1)) / float(n_bays)

        grid = []
        for iu in range(sub_u + 1):
            u = iu / float(sub_u)
            theta = t0 + (t1 - t0) * u
            pleat_z = math.sin(u * math.pi) * 0.75
            col_verts = []
            for iv in range(sub_v + 1):
                v = iv / float(sub_v)
                top_pt, _ = truss_node_points(theta, v)
                pt = Vector((top_pt.x, top_pt.y, top_pt.z + pleat_z))
                col_verts.append(bm_membrane.verts.new(pt))
            grid.append(col_verts)

        for iu in range(sub_u):
            for iv in range(sub_v):
                v00 = grid[iu][iv]
                v10 = grid[iu + 1][iv]
                v11 = grid[iu + 1][iv + 1]
                v01 = grid[iu][iv + 1]
                f = bm_membrane.faces.new((v00, v10, v11, v01))
                for loop, uv in zip(
                    f.loops,
                    [
                        (iu / float(sub_u), iv / float(sub_v)),
                        ((iu + 1) / float(sub_u), iv / float(sub_v)),
                        ((iu + 1) / float(sub_u), (iv + 1) / float(sub_v)),
                        (iu / float(sub_u), (iv + 1) / float(sub_v)),
                    ],
                ):
                    loop[uv_membrane].uv = uv

    truss_obj = finalize_mesh(
        "ROOF_SPACEFRAME_STEEL_TRUSSES",
        bm_truss,
        cols["ROOF_STRUCTURE"],
        [mats["truss_steel"]],
        smooth=True,
    )
    membrane_obj = finalize_mesh(
        "ROOF_PTFE_PLEATED_MEMBRANE",
        bm_membrane,
        cols["ROOF_STRUCTURE"],
        [mats["ptfe_membrane"]],
        smooth=False,  # Flat/faceted per quad highlights the pleated architectural ridges cleanly
    )
    solid_mod = membrane_obj.modifiers.new(name="PTFE_Thickness", type="SOLIDIFY")
    solid_mod.thickness = 0.08
    solid_mod.offset = 0.0

    log(
        f"Built ROOF_SPACEFRAME_STEEL_TRUSSES ({len(truss_obj.data.polygons)} faces) & "
        f"ROOF_PTFE_PLEATED_MEMBRANE ({len(membrane_obj.data.polygons)} faces)"
    )
    return [truss_obj, membrane_obj]


