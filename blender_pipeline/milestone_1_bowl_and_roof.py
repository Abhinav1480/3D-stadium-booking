# 6. REFERENCE GROUND APRON, PITCH MARKER & URBAN SURROUND PLANE
# ==============================================================================
def build_ground_reference(config: dict, cols: dict, mats: dict) -> list:
    bm_turf = bmesh.new()
    uv_turf = bm_turf.loops.layers.uv.new("UVMap")
    rx = config["boundary_rx"] + config["apron_margin"]
    ry = config["boundary_ry"] + config["apron_margin"]
    segs = 96

    center_v = bm_turf.verts.new((0.0, 0.0, 0.0))
    ring_v = []
    for i in range(segs):
        a = (2.0 * math.pi * i) / float(segs)
        ring_v.append(bm_turf.verts.new((rx * math.cos(a), ry * math.sin(a), 0.0)))
    for i in range(segs):
        f = bm_turf.faces.new((center_v, ring_v[i], ring_v[(i + 1) % segs]))
        for loop in f.loops:
            loop[uv_turf].uv = (0.5, 0.5)

    turf_obj = finalize_mesh("GROUND_TURF_REFERENCE", bm_turf, cols["GROUND_REFERENCE"], [mats["turf_reference"]], smooth=True)

    # 22-yard pitch clay reference rectangle along X-axis
    bm_pitch = bmesh.new()
    uv_pitch = bm_pitch.loops.layers.uv.new("UVMap")
    v0 = bm_pitch.verts.new((-10.06, -1.525, 0.03))
    v1 = bm_pitch.verts.new((10.06, -1.525, 0.03))
    v2 = bm_pitch.verts.new((10.06, 1.525, 0.03))
    v3 = bm_pitch.verts.new((-10.06, 1.525, 0.03))
    f = bm_pitch.faces.new((v0, v1, v2, v3))
    for loop in f.loops:
        loop[uv_pitch].uv = (0.5, 0.5)
    pitch_obj = finalize_mesh("PITCH_AXIS_REFERENCE", bm_pitch, cols["GROUND_REFERENCE"], [mats["pitch_reference"]], smooth=False)

    # Large urban surround ground plane so aerial renders never show black void
    bm_sur = bmesh.new()
    uv_sur = bm_sur.loops.layers.uv.new("UVMap")
    s_rad = 650.0
    sv0 = bm_sur.verts.new((-s_rad, -s_rad, -0.05))
    sv1 = bm_sur.verts.new((s_rad, -s_rad, -0.05))
    sv2 = bm_sur.verts.new((s_rad, s_rad, -0.05))
    sv3 = bm_sur.verts.new((-s_rad, s_rad, -0.05))
    sf = bm_sur.faces.new((sv0, sv1, sv2, sv3))
    for loop in sf.loops:
        loop[uv_sur].uv = (0.5, 0.5)
    sur_obj = finalize_mesh("URBAN_SURROUND_GROUND", bm_sur, cols["GROUND_REFERENCE"], [mats["urban_surround"]], smooth=False)

    return [turf_obj, pitch_obj, sur_obj]


