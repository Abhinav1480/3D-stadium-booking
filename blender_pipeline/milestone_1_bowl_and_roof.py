def build_seating_bowl_and_tiers(config: dict, cols: dict, mats: dict) -> list:
    """
    Generates the 8-stand x 3-tier stepped architectural bowl with:
    - Individual row risers and treads per block
    - Recessed vomitory portals cut into each stand
    - Radial stepped aisle stairs with yellow safety nosing
    - Sloped cantilevered concrete soffits underneath Tiers 2 and 3
    - Front-of-tier parapet walls and laminated glass + steel safety balustrades
    """
    log("Generating 3-tier architectural seating bowl across 8 stands...")
    created_objs = []
    bm_bowl = bmesh.new()
    uv_bowl = bm_bowl.loops.layers.uv.new("UVMap")

    bm_rails = bmesh.new()
    uv_rails = bm_rails.loops.layers.uv.new("UVMap")

    # Material indices on bm_bowl:
    # 0 = concrete_treads, 1 = concrete_risers, 2 = concrete_structural,
    # 3 = safety_nosing, 4 = vomitory_dark
    bowl_mats = [
        mats["concrete_treads"],
        mats["concrete_risers"],
        mats["concrete_structural"],
        mats["safety_nosing"],
        mats["vomitory_dark"],
    ]
    rail_mats = [mats["dark_steel"], mats["curtain_glass"]]

    def add_quad(bm, uv_layer, p0, p1, p2, p3, mat_idx=0):
        v0 = bm.verts.new(p0)
        v1 = bm.verts.new(p1)
        v2 = bm.verts.new(p2)
        v3 = bm.verts.new(p3)
        f = bm.faces.new((v0, v1, v2, v3))
        f.material_index = mat_idx
        for loop, uv in zip(f.loops, [(0, 0), (1, 0), (1, 1), (0, 1)]):
            loop[uv_layer].uv = uv
        return f

    def add_tube(bm, p0: Vector, p1: Vector, radius: float, segs: int, mat_idx: int):
        vec = p1 - p0
        length = vec.length
        if length < 0.001:
            return
        mid = (p0 + p1) * 0.5
        rot = Vector((0.0, 0.0, 1.0)).rotation_difference(vec.normalized()).to_matrix().to_4x4()
        mat_xform = Matrix.Translation(mid) @ rot
        res = bmesh.ops.create_cone(
            bm,
            cap_ends=True,
            cap_tris=False,
            segments=segs,
            radius1=radius,
            radius2=radius,
            depth=length,
            matrix=mat_xform,
        )
        for v in res["verts"]:
            for f in v.link_faces:
                f.material_index = mat_idx

    for stand in config["stands"]:
        center_rad = math.radians(stand["center_deg"])
        span_rad = math.radians(stand["span_deg"])
        start_rad = center_rad - span_rad * 0.5
        num_blocks = stand["blocks"]
        block_span = span_rad / float(num_blocks)
        aisle_ang = 0.012  # Radial aisle angular width

        for t_idx, tier in enumerate(config["tiers"]):
            rows = tier["rows"]
            r_depth = tier["row_depth"]
            riser_h = tier["riser_h"]
            in_rx = tier["inner_rx"]
            in_ry = tier["inner_ry"]
            z_base = tier["z_base"]
            v_start = tier["vomitory_row_start"]
            v_end = tier["vomitory_row_end"]

            for b_idx in range(num_blocks):
                b_a0 = start_rad + b_idx * block_span + aisle_ang * 0.5
                b_a1 = start_rad + (b_idx + 1) * block_span - aisle_ang * 0.5

                # Subdivide each block arc into 4 angular sub-segments for smooth curvature
                sub_segs = 4
                sub_da = (b_a1 - b_a0) / float(sub_segs)

                # Determine if the center sub-segment of odd blocks has a vomitory portal
                has_vomitory = (b_idx % 2 == 1)

                for s_idx in range(sub_segs):
                    a0 = b_a0 + s_idx * sub_da
                    a1 = a0 + sub_da
                    c0, s0 = math.cos(a0), math.sin(a0)
                    c1, s1 = math.cos(a1), math.sin(a1)

                    is_vom_slice = has_vomitory and (s_idx in (1, 2))

                    # 1. Front parapet wall of the tier (on Row 0 inner edge)
                    p_z_bot = 0.0 if t_idx == 0 else z_base - 0.65
                    p_z_top = z_base + 0.95
                    add_quad(
                        bm_bowl, uv_bowl,
                        (in_rx * c0, in_ry * s0, p_z_bot),
                        (in_rx * c1, in_ry * s1, p_z_bot),
                        (in_rx * c1, in_ry * s1, p_z_top),
                        (in_rx * c0, in_ry * s0, p_z_top),
                        mat_idx=2,
                    )

                    # Glass safety balustrade on top of front parapet
                    g_rx = in_rx + 0.12
                    g_ry = in_ry + 0.12
                    add_quad(
                        bm_rails, uv_rails,
                        (g_rx * c0, g_ry * s0, p_z_top),
                        (g_rx * c1, g_ry * s1, p_z_top),
                        (g_rx * c1, g_ry * s1, p_z_top + 0.75),
                        (g_rx * c0, g_ry * s0, p_z_top + 0.75),
                        mat_idx=1,
                    )
                    add_tube(
                        bm_rails,
                        Vector((g_rx * c0, g_ry * s0, p_z_top + 0.78)),
                        Vector((g_rx * c1, g_ry * s1, p_z_top + 0.78)),
                        radius=0.035,
                        segs=8,
                        mat_idx=0,
                    )

                    # 2. Stepped Rows (Riser + Tread)
                    for r_idx in range(rows):
                        rx0 = in_rx + r_idx * r_depth
                        ry0 = in_ry + r_idx * r_depth
                        rx1 = rx0 + r_depth
                        ry1 = ry0 + r_depth

                        z_bot = z_base + r_idx * riser_h
                        z_top = z_bot + riser_h

                        if is_vom_slice and (v_start <= r_idx <= v_end):
                            # Vomitory opening: flat recessed dark tunnel floor & portal lintel
                            z_vom_floor = z_base + v_start * riser_h
                            add_quad(
                                bm_bowl, uv_bowl,
                                (rx0 * c0, ry0 * s0, z_vom_floor),
                                (rx0 * c1, ry0 * s1, z_vom_floor),
                                (rx1 * c1, ry1 * s1, z_vom_floor),
                                (rx1 * c0, ry1 * s0, z_vom_floor),
                                mat_idx=4,
                            )
                            if r_idx == v_end:
                                # Back dark portal wall of the vomitory tunnel
                                z_vom_top = z_base + (v_end + 1) * riser_h
                                add_quad(
                                    bm_bowl, uv_bowl,
                                    (rx1 * c0, ry1 * s0, z_vom_floor),
                                    (rx1 * c1, ry1 * s1, z_vom_floor),
                                    (rx1 * c1, ry1 * s1, z_vom_top),
                                    (rx1 * c0, ry1 * s0, z_vom_top),
                                    mat_idx=4,
                                )
                            continue

                        # Vertical Riser face
                        add_quad(
                            bm_bowl, uv_bowl,
                            (rx0 * c0, ry0 * s0, z_bot),
                            (rx0 * c1, ry0 * s1, z_bot),
                            (rx0 * c1, ry0 * s1, z_top),
                            (rx0 * c0, ry0 * s0, z_top),
                            mat_idx=1,
                        )
                        # Horizontal Tread surface
                        add_quad(
                            bm_bowl, uv_bowl,
                            (rx0 * c0, ry0 * s0, z_top),
                            (rx0 * c1, ry0 * s1, z_top),
                            (rx1 * c1, ry1 * s1, z_top),
                            (rx1 * c0, ry1 * s0, z_top),
                            mat_idx=0,
                        )

                    # 3. Sloped Under-Tier Cantilever Soffit & Back Wall
                    out_rx = in_rx + rows * r_depth
                    out_ry = in_ry + rows * r_depth
                    z_back_top = z_base + rows * riser_h
                    add_quad(
                        bm_bowl, uv_bowl,
                        (in_rx * c0, in_ry * s0, p_z_bot),
                        (out_rx * c0, out_ry * s0, z_back_top - 1.2),
                        (out_rx * c1, out_ry * s1, z_back_top - 1.2),
                        (in_rx * c1, in_ry * s1, p_z_bot),
                        mat_idx=2,
                    )
                    # Rear parapet wall at top of tier
                    add_quad(
                        bm_bowl, uv_bowl,
                        (out_rx * c0, out_ry * s0, z_back_top - 1.2),
                        (out_rx * c1, out_ry * s1, z_back_top - 1.2),
                        (out_rx * c1, out_ry * s1, z_back_top + 2.4),
                        (out_rx * c0, out_ry * s0, z_back_top + 2.4),
                        mat_idx=2,
                    )

                # 4. Radial Stepped Aisle Stairs + Safety Yellow Nosings + Central Handrail
                aisle_a0 = b_a1
                aisle_a1 = b_a1 + aisle_ang
                ca0, sa0 = math.cos(aisle_a0), math.sin(aisle_a0)
                ca1, sa1 = math.cos(aisle_a1), math.sin(aisle_a1)
                cam, sam = math.cos((aisle_a0 + aisle_a1) * 0.5), math.sin((aisle_a0 + aisle_a1) * 0.5)

                for r_idx in range(rows):
                    rx0 = in_rx + r_idx * r_depth
                    ry0 = in_ry + r_idx * r_depth
                    rx1 = rx0 + r_depth
                    ry1 = ry0 + r_depth
                    z_top = z_base + (r_idx + 1) * riser_h + 0.015
                    add_quad(
                        bm_bowl, uv_bowl,
                        (rx0 * ca0, ry0 * sa0, z_top),
                        (rx0 * ca1, ry0 * sa1, z_top),
                        (rx1 * ca1, ry1 * sa1, z_top),
                        (rx1 * ca0, ry1 * sa0, z_top),
                        mat_idx=3,
                    )

                # Sloped tubular handrail running up the radial aisle
                r_start = Vector((in_rx * cam, in_ry * sam, z_base + 1.0))
                r_end = Vector(((in_rx + rows * r_depth) * cam, (in_ry + rows * r_depth) * sam, z_base + rows * riser_h + 1.0))
                add_tube(bm_rails, r_start, r_end, radius=0.032, segs=8, mat_idx=0)

    bowl_obj = finalize_mesh("STADIUM_STEPPED_BOWL_TIERS", bm_bowl, cols["STADIUM_BOWL"], bowl_mats, smooth=False)
    rails_obj = finalize_mesh("TIER_BALUSTRADES_AND_HANDRAILS", bm_rails, cols["STADIUM_BOWL"], rail_mats, smooth=True)
    created_objs.extend([bowl_obj, rails_obj])
    log(f"Built STADIUM_STEPPED_BOWL_TIERS ({len(bowl_obj.data.polygons)} faces) & TIER_BALUSTRADES_AND_HANDRAILS")
    return created_objs


