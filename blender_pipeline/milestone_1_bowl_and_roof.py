    scene.render.image_settings.file_format = "PNG"

    # Set default camera and save actual .blend file
    scene.camera = cameras["view1_aerial_bowl"]
    blend_path = os.path.join(out_dir, config["blend_filename"])
    bpy.ops.wm.save_as_mainfile(filepath=blend_path)
    log(f"Saved Blender project file: {blend_path} ({os.path.getsize(blend_path)} bytes)")

    rendered_files = {}
    for view_key, cam_obj in cameras.items():
        scene.camera = cam_obj
        img_path = os.path.join(out_dir, f"milestone1_{view_key}.png")
        scene.render.filepath = img_path
        t0 = time.time()
        log(f"Rendering Cycles preview [{view_key}] via {cam_obj.name} -> {img_path} ...")
        bpy.ops.render.render(write_still=True)
        elapsed = time.time() - t0
        log(f"Finished [{view_key}] in {elapsed:.1f}s ({os.path.getsize(img_path)} bytes)")
        rendered_files[view_key] = img_path

    # Collect geometry & scene telemetry
    mesh_stats = []
    total_verts = 0
    total_faces = 0
    for obj in bpy.data.objects:
        if obj.type == "MESH":
            v_cnt = len(obj.data.vertices)
            f_cnt = len(obj.data.polygons)
            total_verts += v_cnt
            total_faces += f_cnt
            mesh_stats.append({"name": obj.name, "vertices": v_cnt, "faces": f_cnt})

    telemetry = {
        "milestone": "Milestone 1 — Stadium Bowl, Multi-Tier Seating Architecture, Exterior Colonnade & Space-Frame Roof",
        "blender_version": bpy.app.version_string,
        "blend_file": blend_path,
        "blend_file_size_bytes": os.path.getsize(blend_path),
        "renders": rendered_files,
        "total_vertices": total_verts,
        "total_faces": total_faces,
        "meshes": mesh_stats,
    }
    telemetry_path = os.path.join(out_dir, "milestone1_telemetry.json")
    with open(telemetry_path, "w", encoding="utf-8") as f:
        json.dump(telemetry, f, indent=2)
    log(f"Wrote telemetry manifest: {telemetry_path}")
    return telemetry


